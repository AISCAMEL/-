  function deepCopy(o) { return JSON.parse(JSON.stringify(o)); }

  function load() {
    try {
      var s = localStorage.getItem(KEY);
      if (!s) return deepCopy(DEFAULTS);
      var d = JSON.parse(s);
      // 互換: 欠けたキーは既定で補う
      ['notices', 'courses', 'scripts', 'docs'].forEach(function (k) {
        if (!Array.isArray(d[k])) d[k] = deepCopy(DEFAULTS[k]);
      });
      if (!d.updatedAt) d.updatedAt = DEFAULTS.updatedAt;
      return d;
    } catch (e) { return deepCopy(DEFAULTS); }
  }

  function save(d) {
    d.updatedAt = fmtNow();
    try { localStorage.setItem(KEY, JSON.stringify(d)); } catch (e) {}
    return d;
  }

  function reset() {
    var d = deepCopy(DEFAULTS);
    save(d);
    return d;
  }

  function fmtNow() {
    var d = new Date();
    function p(n) { return ('0' + n).slice(-2); }
    return d.getFullYear() + '-' + p(d.getMonth() + 1) + '-' + p(d.getDate()) + ' ' + p(d.getHours()) + ':' + p(d.getMinutes());
  }

  function newId(prefix) {
    return prefix + Date.now().toString(36) + Math.random().toString(36).slice(2, 5);
  }

  // 他タブでの変更を購読
  function onChange(cb) {
    window.addEventListener('storage', function (e) {
      if (e.key === KEY) { try { cb(load()); } catch (err) {} }
    });
  }

  return {
    KEY: KEY,
    load: load, save: save, reset: reset,
    newId: newId, fmtNow: fmtNow, onChange: onChange,
    defaults: function () { return deepCopy(DEFAULTS); }
  };
