/** はじめの記事を入れる（すでに入れたものは飛ばす）。入れた数を返す。 */
function apprex_labo_seed_starter() {
	if ( ! post_type_exists( 'apprex_labo_post' ) ) {
		return 0;
	}
	$done = (array) get_option( 'apprex_labo_seeded', array() );
	$n    = 0;
	$i    = 0;
	foreach ( apprex_labo_starter_posts() as $key => $a ) {
		$i++;
		if ( in_array( $key, $done, true ) ) {
			continue;
		}
		$id = wp_insert_post(
			array(
				'post_type'    => 'apprex_labo_post',
				'post_status'  => 'publish',
				'post_title'   => $a[1],
				'post_excerpt' => $a[2],
				'post_content' => $a[4],
				'menu_order'   => $i,
				// 新しい順に並ぶので、1本目がいちばん上に来るよう少しずつ時間をずらす。
				'post_date'    => wp_date( 'Y-m-d H:i:s', time() - $i * 60 ),
			),
			true
		);
		if ( is_wp_error( $id ) || ! $id ) {
			continue;
		}
		if ( ! term_exists( $a[0], 'apprex_labo_cat' ) ) {
			wp_insert_term( $a[0], 'apprex_labo_cat' );
		}
		wp_set_object_terms( $id, $a[0], 'apprex_labo_cat' );
		update_post_meta( $id, 'apprex_labo_cta', $a[3] );
		update_post_meta( $id, 'apprex_labo_seed_key', $key );
		$done[] = $key;
		$n++;
	}
	update_option( 'apprex_labo_seeded', $done, false );
	return $n;
}

/* 管理画面を開いたときに1回だけ入れる。 */
add_action(
	'admin_init',
	function () {
		if ( wp_doing_ajax() || ! current_user_can( 'edit_posts' ) ) {
			return;
		}
		if ( count( (array) get_option( 'apprex_labo_seeded', array() ) ) >= count( apprex_labo_starter_posts() ) ) {
			return;
		}
		apprex_labo_seed_starter();
	}
);
